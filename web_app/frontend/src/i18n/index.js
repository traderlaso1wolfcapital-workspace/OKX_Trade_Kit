/**
 * Custom hook to get current language and translation function `t(key, fallback)`
 */
export function useTranslation() {
  const [lang, setLang] = useState(() => {
    return localStorage.getItem("tls1_app_language") || "vi";
  });

  useEffect(() => {
    const handleLangChange = (e) => {
      if (e?.detail) {
        setLang(e.detail);
      } else {
        setLang(localStorage.getItem("tls1_app_language") || "vi");
      }
    };

    window.addEventListener("tls1_language_changed", handleLangChange);
    return () => {
      window.removeEventListener("tls1_language_changed", handleLangChange);
    };
  }, []);

  const t = (key, fallback = "") => {
    const dict = translations[lang] || translations.vi;
    return dict[key] || translations.vi[key] || fallback || key;
  };

  return { lang, t };
}
